import 'package:drift/drift.dart';
import 'package:drift/native.dart';
import 'package:log_trail_drift/log_trail_drift.dart';

part 'test_database.g.dart';

/// The plain log table, declared as the README shows. The row class is named
/// explicitly: drift would otherwise call it `LogEntry`, which clashes with
/// `log_trail`'s `LogEntry`.
@DataClassName('LogEntryRow')
@TableIndex(name: 'log_entries_by_time', columns: {#time, #id})
class LogEntries extends Table with LogEntryColumns {}

/// A table of the application's own with the log columns mixed in and an
/// extra column: what a user integrating the store into an existing schema
/// writes.
@TableIndex(name: 'tenant_logs_by_time', columns: {#time, #id})
class TenantLogs extends Table with LogEntryColumns {
  TextColumn get tenant => text()();
}

/// The database of the tests, generated by drift as in any application.
@DriftDatabase(tables: [LogEntries, TenantLogs])
class TestDatabase extends _$TestDatabase {
  TestDatabase(super.e);

  TestDatabase.memory() : super(NativeDatabase.memory());

  @override
  int get schemaVersion => 1;
}
